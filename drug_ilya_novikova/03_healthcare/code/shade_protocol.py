# ТЕНЬ КУБАНИ: логика жарового протокола муниципалитета
# Уровни запускаются по прогнозу метеослужбы; у каждого уровня свой набор мер.

LEVELS = {
    "жёлтый": {
        "условие": "жара 3+ дня подряд, максимум >= 36",
        "меры": ["обзвон пожилых из реестра соцзащиты",
                 "памятки дворникам и курьерам: сдвиг работ на утро",
                 "проверка питьевых точек"],
    },
    "красный": {
        "условие": "волна 5+ дней или максимум >= 40",
        "меры": ["прохладные комнаты в библиотеках и МФЦ",
                 "усиление питьевых точек на теневых маршрутах",
                 "волонтёрский обход одиноких пожилых",
                 "смещение массовых мероприятий на вечер"],
    },
}

def level_for(days_hot, t_max):
    if days_hot >= 5 or t_max >= 40:
        return "красный"
    if days_hot >= 3 and t_max >= 36:
        return "жёлтый"
    return "штатный"

if __name__ == "__main__":
    lvl = level_for(days_hot=6, t_max=40.2)
    print("уровень:", lvl)
    for m in LEVELS[lvl]["меры"]:
        print(" -", m)
    # Обкатка 24-29.07.2026: 137 обзвоненных, прохладная комната 89 посещений.
