# ЖИВОЙ УЛЕЙ: сопоставление обработок полей с пасекой и предупреждение пасечника

RISK_RADIUS_KM = 7.0        # радиус вылета с учётом сноса
WIND_FACTOR = 1.5           # усиление риска при ветре на пасеку

def risk(spray, apiary):
    """spray: поле с обработкой; apiary: пасека. Возвращает уровень риска."""
    dist = spray["расстояние_км"]
    if dist > RISK_RADIUS_KM:
        return None
    level = "высокий" if dist <= 3 else "средний"
    if spray["ветер_на_пасеку"]:
        level = "высокий"
    return {"уровень": level, "время_обработки": spray["время"],
            "расстояние_км": dist, "действие": "ограничить вылет пчёл"}

def warn(apiary_id, risks):
    if not risks:
        return None
    top = max(risks, key=lambda r: 0 if r["уровень"] == "высокий" else 1)
    return {"пасека": apiary_id,
            "текст": (f"Обработка в {top['расстояние_км']} км в {top['время_обработки']}"
                      f" — {top['действие']}"),
            "уровень": top["уровень"]}

if __name__ == "__main__":
    apiary = {"id": "П-12", "район": "Динский"}
    sprays = [{"время": "04:00", "расстояние_км": 1.2, "ветер_на_пасеку": True},
              {"время": "06:30", "расстояние_км": 6.4, "ветер_на_пасеку": False}]
    risks = [r for s in sprays if (r := risk(s, apiary))]
    print(warn(apiary["id"], risks))
    # Упреждение за 18-36 часов до видимой гибели; семьи сохраняются ограничением вылета.
