# ДОСТУПНЫЙ КУРОРТ: конструктор паспорта доступности объекта
# 42 контрольных параметра в пяти категориях; статус — по минимальному звену маршрута.

NORMS = {
    "уклон_пандуса_проц": 5.0,      # не более, %
    "ширина_проёма_см": 90.0,       # не менее, см
    "усилие_двери_кгс": 5.0,        # не более, кгс
    "высота_порога_см": 1.4,        # не более, см
}

def check(param, value):
    """Возвращает 'соответствует' / 'не соответствует' по нормативу."""
    if param in ("ширина_проёма_см",):
        return "соответствует" if value >= NORMS[param] else "не соответствует"
    return "соответствует" if value <= NORMS[param] else "не соответствует"

def status(results):
    """Статус объекта: по худшему звену маршрута."""
    if all(r == "соответствует" for r in results.values()):
        return "доступно"
    if any(r == "недоступно_полностью" for r in results.values()):
        return "недоступно"
    return "доступно с помощью"

def passport(obj, measurements, photos=()):
    checks = {k: check(k, v) for k, v in measurements.items()}
    return {
        "объект": obj,
        "параметров_проверено": len(checks),
        "проверки": checks,
        "статус": status(checks),
        "фотофиксация": len(photos),
        "рекомендации": [k for k, v in checks.items() if v == "не соответствует"],
    }

if __name__ == "__main__":
    p = passport("Санаторий «Пример», Анапа",
                 {"уклон_пандуса_проц": 7.8, "ширина_проёма_см": 82,
                  "усилие_двери_кгс": 4.2, "высота_порога_см": 1.0},
                 photos=("a.jpg", "b.jpg"))
    print(p["статус"], "— рекомендации:", p["рекомендации"])
