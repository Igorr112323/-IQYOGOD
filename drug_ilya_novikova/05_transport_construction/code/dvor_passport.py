# ДВОР БЕЗ СТУПЕНЕЙ: генератор паспорта двора
# Паспорт = индекс + карта барьеров + приоритеты жителей + сметы.

def make_passport(address, index, barriers, residents_top):
    """barriers: список словарей с описанием, типом и сметой.
    residents_top: порядок приоритетов по итогам разбора в ТСЖ."""
    quick = [b for b in barriers if b["смета"] <= 80_000]
    capital = [b for b in barriers if b["смета"] > 80_000]
    return {
        "двор": address,
        "индекс доступности": index,
        "барьеров": len(barriers),
        "быстрые победы": [b["что"] for b in quick],
        "капитальные меры": [b["что"] for b in capital],
        "приоритет жителей": residents_top,
        "сумма быстрых мер, руб": sum(b["смета"] for b in quick),
        "сумма капитальных, руб": sum(b["смета"] for b in capital),
    }

