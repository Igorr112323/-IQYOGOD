# ДВОР БЕЗ СТУПЕНЕЙ: калькулятор индекса доступности двора (0-100)
# 5 групп чек-листа с весами; балл пункта 0/0,5/1.

GROUPS = {
    "пути к подъездам": 0.30,
    "подъезды и входы": 0.25,
    "освещение": 0.15,
    "места отдыха и навигация": 0.15,
    "тропы к остановкам и магазинам": 0.15,
}

def group_score(items):
    """items: список оценок 0 / 0.5 / 1."""
    return sum(items) / len(items) if items else 0.0

def yard_index(scores: dict) -> float:
    total = 0.0
    for g, w in GROUPS.items():
        total += w * group_score(scores.get(g, []))
    return round(total * 100, 1)

def verdict(index):
    if index < 40: return "красный: приоритет быстрых побед"
    if index < 60: return "жёлтый: план УК + программа благоустройства"
    return "зелёный: поддерживающие меры"

if __name__ == "__main__":
    zakharova = {
        "пути к подъездам": [0, 0.5, 0, 1],
        "подъезды и входы": [0, 0, 0.5],
        "освещение": [0, 0.5],
        "места отдыха и навигация": [0.5, 0.5, 1],
        "тропы к остановкам и магазинам": [0, 0.5, 0],
    }
    idx = yard_index(zakharova)
    print(f"двор на Захарова: индекс {idx} — {verdict(idx)}")
