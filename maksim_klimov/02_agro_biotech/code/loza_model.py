# ВТОРАЯ ЛОЗА: модель режимов субкритической экстракции под сорт и кондиции выжимки
# Субкритическая вода: 150-190 С под давлением 10-15 бар, без органических растворителей.
# Модель подбирает температуру и время цикла под партию сырья.

GRAPE_PRESETS = {
    "Красностоп": {"t_c": 180, "time_min": 26, "bar": 14},
    "Шардоне":    {"t_c": 165, "time_min": 22, "bar": 12},
    "Саперави":   {"t_c": 185, "time_min": 30, "bar": 15},
    "Мерло":      {"t_c": 175, "time_min": 24, "bar": 13},
}

def recommend_mode(variety, moisture_pct, residual_sugar_pct):
    """Возвращает режим с поправками на влажность и остаточный сахар выжимки."""
    base = GRAPE_PRESETS.get(variety, {"t_c": 170, "time_min": 24, "bar": 12})
    mode = dict(base)
    if moisture_pct > 55:                      # мокрая выжимка — меньше разбавляем, короче цикл
        mode["time_min"] = max(18, mode["time_min"] - 4)
    if residual_sugar_pct > 3.0:               # сахар карамелизуется — снижаем температуру
        mode["t_c"] = max(150, mode["t_c"] - 10)
        mode["time_min"] += 3
    mode["предохранительный_клапан_бар"] = mode["bar"] + 3
    return mode

def expected_yield_kg_per_ton(variety):
    """Ожидаемый выход сухого экстракта, кг/т (по данным 28 экстракций прототипа)."""
    table = {"Красностоп": 3.2, "Шардоне": 2.9, "Саперави": 3.4, "Мерло": 3.1}
    return table.get(variety, 3.1)

if __name__ == "__main__":
    m = recommend_mode("Саперави", moisture_pct=48, residual_sugar_pct=1.8)
    print("режим Саперави:", m)
    print("ожидаемый выход Саперави:", expected_yield_kg_per_ton("Саперави"), "кг/т")
    # Протокол сезонных испытаний 2026: 28 экстракций, средний выход 3,1 кг/т.
