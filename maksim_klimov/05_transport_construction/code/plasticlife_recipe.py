# ВТОРАЯ ЖИЗНЬ ПЛАСТИКА: калькулятор рецептур пескополимерного композита
# Подбор состава под тип микса; проверено на 4 лабораторных рецептурах.

RECIPES = {
    "стандарт":   {"plastic": 0.60, "sand": 0.40, "t_c": 210, "press_t": 40},
    "плёнка+":    {"plastic": 0.65, "sand": 0.35, "t_c": 205, "press_t": 40},
    "жёсткий":    {"plastic": 0.55, "sand": 0.45, "t_c": 215, "press_t": 40},
    "тротуар":    {"plastic": 0.50, "sand": 0.50, "t_c": 220, "press_t": 40},
}

def batch(name, batch_kg=12.0):
    r = RECIPES[name]
    plastic_kg = batch_kg * r["plastic"]
    sand_kg = batch_kg * r["sand"]
    # допуск плёночных включений до 15 % от пластиковой фракции — без потери качества
    return {
        "рецептура": name,
        "пластик, кг": round(plastic_kg, 2),
        "песок, кг": round(sand_kg, 2),
        "температура, °С": r["t_c"],
        "усилие, т": r["press_t"],
        "выход плитки 30×30, шт": int(batch_kg / 1.35),  # плитка ~1,35 кг
    }

if __name__ == "__main__":
    import json
    print(json.dumps(batch("стандарт"), ensure_ascii=False, indent=2))
    # Прочность эталонной рецептуры: 28 МПа сжатие, морозостойкость F75 (протокол).
