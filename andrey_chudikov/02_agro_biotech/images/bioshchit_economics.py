# -*- coding: utf-8 -*-
# БИОЩИТ-КУБАНЬ: экономика хозяйства и производителя, Монте-Карло 3 000 псевдосезонов.
# Только стандартная библиотека (без numpy/matplotlib).
# Модель: 1 000 га озимой пшеницы; биозащита вместо химического протравителя.
# Эффект хозяйства — предотвращённые потери всходов (сохранённый урожай), руб.
# Маржа производителя — линия мелкосерийного выпуска: 10 тыс. га-доз/год,
# себестоимость 28 руб./га-дозу, капзатраты линии 980 тыс. руб.
import random

random.seed(7)
N = 3000
AREA = 1000.0           # га
PRICE_WHEAT = 13500.0   # руб./т
YIELD = 48.0            # ц/га базовая
DOSES_YEAR = 10000      # га-доз/год выпуска линии
COST_DOSE = 28.0        # себестоимость, руб./га-дозу
CAPEX_LINE = 0.98       # млн руб.

farm_effect = []        # сохранённый урожай, млн руб./сезон
margins = []            # маржа производителя, млн руб./год
paybacks = []           # окупаемость линии, сезонов
for _ in range(N):
    rel_eff = random.triangular(0.5, 0.75, 1.0)            # био относительно эталон-химии
    saved_pct = random.triangular(0.7, 1.0, 1.35) * rel_eff  # % площади, где всходы сохранены
    farm_effect.append(AREA * YIELD * 100 / 1e6 * (saved_pct / 100) * PRICE_WHEAT)
    price = random.uniform(88.0, 100.0)                  # отпускная цена, руб./га-дозу
    margin = (price - COST_DOSE) * DOSES_YEAR / 1e6
    margins.append(margin)
    paybacks.append(CAPEX_LINE / margin)

farm_effect.sort(); margins.sort(); paybacks.sort()
med = lambda v: v[len(v) // 2]
p = lambda v, q: v[int(len(v) * q)]

print("БИОЩИТ-КУБАНЬ: Монте-Карло %d псевдосезонов (1 000 га озимой пшеницы)" % N)
print("Эффект хозяйства (сохранённый урожай): медиана %.0f тыс. руб./сезон (p10 %.0f, p90 %.0f)"
      % (med(farm_effect), p(farm_effect, 0.10), p(farm_effect, 0.90)))
print("Маржа производителя (10 тыс. га-доз/год, себестоимость 28 руб.): медиана %.2f млн руб./год"
      % med(margins))
print("Окупаемость капзатрат линии 980 тыс. руб.: медиана %.2f сезона" % med(paybacks))
