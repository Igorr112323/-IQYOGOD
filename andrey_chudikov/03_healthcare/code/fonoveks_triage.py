# ФОНО-ВЕКС: триаж по результатам голосового скрининга
# Маршрутизация: норма / повторный контакт / приоритетный патронаж.
# Пороги подобраны по валидационной выборке (эталон GDS-15).

THRESHOLD_WATCH = 0.35        # повторный контакт через 2 недели
THRESHOLD_PRIORITY = 0.62     # приоритетный патронаж в течение 72 часов

def score_from_features(features):
    """Скрининговый балл 0..1 (в изделии — градиентный бустинг, здесь — линейная форма)."""
    rate = features["слоговая_скорость"] or 3.5
    pauses = features["паузы"]["доля_пауз"]
    f0_var = features["вариабельность_f0"] or 0.1
    repeats = features["индекс_повторов"]
    s = (0.30 * max(0.0, 1.0 - rate / 3.5)
         + 0.30 * min(1.0, pauses / 0.5)
         + 0.15 * max(0.0, 1.0 - f0_var / 0.12)
         + 0.25 * min(1.0, repeats / 0.20))
    return round(min(1.0, s), 3)

def triage(score, call_completed):
    if not call_completed:
        return {"маршрут": "повторный обзвон", "срок": "48 часов"}
    if score >= THRESHOLD_PRIORITY:
        return {"маршрут": "приоритетный патронаж", "срок": "72 часа",
                "получатель": "участковая служба + родственники (по согласию)"}
    if score >= THRESHOLD_WATCH:
        return {"маршрут": "повторный контакт", "срок": "2 недели"}
    return {"маршрут": "плановый график", "срок": "следующий цикл"}

if __name__ == "__main__":
    feats = {"слоговая_скорость": 2.1,
             "паузы": {"доля_пауз": 0.44, "средняя_с": 0.9},
             "вариабельность_f0": 0.05, "индекс_повторов": 0.18}
    score = score_from_features(feats)
    print("балл:", score)
    print("триаж:", triage(score, call_completed=True))
