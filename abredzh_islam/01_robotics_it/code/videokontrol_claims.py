# МУНИЦИПАЛЬНЫЙ ВИДЕОКОНТРОЛЬ: формирование претензионного журнала
# Каждое подтверждённое нарушение -> запись с основанием и суммой неустойки.

PENALTY = {
    "срыв рейса": 15000.0,        # руб. за случай (по типовому контракту)
    "нарушение интервала": 1500.0,
    "простой техники оплаченный": 2200.0,  # руб./час
}

def claim_record(contract_id, event_type, when, evidence, qty=1):
    rate = PENALTY[event_type]
    return {
        "контракт": contract_id,
        "событие": event_type,
        "дата": when,
        "кол-во": qty,
        "сумма, руб": round(rate * qty, 2),
        "доказательство": evidence,     # ID видеозаписи + метки камер
    }

def journal_total(journal):
    return round(sum(r["сумма, руб"] for r in journal), 2)

if __name__ == "__main__":
    journal = [
        claim_record("К-2026-018", "срыв рейса", "2026-04-19 07:40", "камеры К-03, К-11"),
        claim_record("К-2026-018", "нарушение интервала", "2026-04-19", "камера К-07", qty=14),
        claim_record("К-2026-021", "простой техники оплаченный", "2026-05-02", "камеры О-02, О-05", qty=26),
    ]
    for r in journal:
        print(r)
    print("итого неустоек:", journal_total(journal), "руб.")
