# ЗЕРНОВОЙ ПАСПОРТ: формирование паспорта партии и маршрутизация режимов

MOISTURE_LIMIT = 14.0      # выше — доработка до смешения
PROTEIN_CLASS = 13.5       # выше — отдельное хранение по классу

def make_passport(vehicle_id, weight_t, analysis, scale_id, ts):
    return {"партия": f"{scale_id}-{vehicle_id}-{ts}",
            "масса_т": weight_t,
            "влажность": analysis["влажность"],
            "натура": analysis["натура"],
            "протеин": analysis["протеин"],
            "клейковина": analysis["клейковина"],
            "примесь": analysis["примесь"],
            "фото": "приложено", "весовая": scale_id}

def route(passport):
    if passport["влажность"] > MOISTURE_LIMIT:
        drying_cost = round(passport["масса_т"] * 120 *
                            (passport["влажность"] - MOISTURE_LIMIT), 0)  # руб.
        return {"режим": "доработка до смешения",
                "расчёт_сушки_руб": drying_cost}
    if passport["протеин"] >= PROTEIN_CLASS:
        return {"режим": "отдельное хранение по классу",
                "класс": "высокопротеиновая"}
    return {"режим": "приём в общий поток"}

if __name__ == "__main__":
    wet = make_passport("К-114", 32.4,
                        {"влажность": 16.8, "натура": 780, "протеин": 12.9,
                         "клейковина": 24, "примесь": 1.2},
                        "ВЕС-2", "060726-0915")
    print("паспорт:", wet)
    print("маршрут:", route(wet))
    dry = make_passport("К-201", 41.0,
                        {"влажность": 12.9, "натура": 802, "протеин": 14.2,
                         "клейковина": 28, "примесь": 0.6},
                        "ВЕС-2", "060726-1012")
    print("маршрут высокопротеиновой:", route(dry))
