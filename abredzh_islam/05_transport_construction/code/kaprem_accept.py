# КАПРЕМОНТ-КОНТРОЛЬ: сверка измерений приёмки с допусками проекта
# Отклонение блокирует подписание этапа до устранения.

TOLERANCES = {          # допуск: (минимум, максимум)
    "толщина_фасада_мм": (4.0, 8.0),
    "уклон_кровли_проц": (2.0, 5.0),
    "влажность_основания_проц": (0.0, 6.0),
    "перепад_пола_мм_м": (0.0, 2.0)}

def check_point(point):
    """point: {параметр, значение, геометка, время}."""
    tol = TOLERANCES.get(point["параметр"])
    if tol is None:
        return {"статус": "нет допуска", "подписание": "заблокировано"}
    ok = tol[0] <= point["значение"] <= tol[1]
    return {"статус": "в допуске" if ok else "отклонение",
            "подписание": "разрешено" if ok else "заблокировано до устранения",
            "допуск": tol, "значение": point["значение"]}

def accept_stage(points):
    """Этот подписывается только если все точки в допуске."""
    results = [check_point(p) for p in points]
    blocked = [r for r in results if r["подписание"] != "разрешено"]
    return {"этап": points[0].get("этап"), "точек": len(results),
            "отклонений": len(blocked),
            "акт": "подписан" if not blocked else "не подписан"}

