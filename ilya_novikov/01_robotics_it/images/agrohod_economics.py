# -*- coding: utf-8 -*-
# АГРОХОД-2: экономия СЗР у хозяйства и окупаемость серийной платформы,
# Монте-Карло 3 000 сценариев. Только стандартная библиотека (без numpy).
# Услуга опрыскивания интенсивного сада: 250 га, 12 обработок/сезон, 2,5 тыс. руб./обработку/га,
# загрузка 60 %, эксплуатация (топливо, СО, амортизация) 1,1 млн руб./сезон.
# Экономия хозяйства: −31 % расхода рабочей жидкости и СЗР относительно базового опрыскивателя.
import random

random.seed(8)
N = 3000
AREA = 250.0            # га в обслуживании
TRIPS = 12              # обработок за сезон
PRICE = 2500.0          # руб./обработку/га
COST_SERIES = 1.9e6     # руб., серийная платформа
OPEX = 1.1e6            # руб./сезон, эксплуатация

saves_ha = []
margins = []
paybacks = []
for _ in range(N):
    save_frac = random.triangular(0.26, 0.31, 0.36)          # экономия жидкости/СЗР, доля
    chem_rub_ha = random.triangular(8500, 10500, 13000)      # руб./га СЗР+вода за 12 обработок (интенсивный сад)
    saves_ha.append(save_frac * chem_rub_ha)                 # экономия хозяйства, руб./га/сезон
    load = random.triangular(0.48, 0.58, 0.73)           # загрузка парка
    revenue = AREA * TRIPS * PRICE * load                    # руб./сезон
    margin = revenue - OPEX
    margins.append(margin)
    paybacks.append(COST_SERIES / margin)                    # сезонов

saves_ha.sort(); margins.sort(); paybacks.sort()
med = lambda v: v[len(v) // 2]

print("АГРОХОД-2: Монте-Карло %d сценариев (250 га, 12 обработок)" % N)
print("Экономия хозяйства: медиана %.0f руб./га/сезон" % med(saves_ha))
print("Маржа услуги: медиана %.1f млн руб./сезон" % (med(margins) / 1e6))
print("Окупаемость серийной платформы 1,9 млн руб.: медиана %.2f сезона" % med(paybacks))
