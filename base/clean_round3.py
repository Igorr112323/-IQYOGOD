misses = []
for folder, subs in PATCHES.items():
    p = pathlib.Path(folder) / "ЗАЯВКА.md"
    t = p.read_text(encoding="utf-8")
    for kind, a, b in subs:
        if kind == "s":
            if a not in t:
                misses.append((folder, a[:70])); continue
            t = t.replace(a, b, 1)
        else:
            t2 = re.sub(a, b, t, count=1, flags=re.M)
            if t2 == t:
                misses.append((folder, "RE: " + a[:60])); continue
            t = t2
    p.write_text(t, encoding="utf-8")

