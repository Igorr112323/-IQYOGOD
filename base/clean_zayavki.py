for folder in sorted(S9):
    path = os.path.join(ROOT, folder, "ЗАЯВКА.md")
    t = open(path, encoding="utf-8").read()
    orig = t

    # 1) п.9: заменить секцию до блока таблиц протокола
    m = re.search(r"## 9\. РЕЗУЛЬТАТЫ, ДОСТИГНУТЫЕ К НАСТОЯЩЕМУ ВРЕМЕНИ.*?(?=### Ключевые таблицы протокола)", t, re.S)
    assert m, folder + ": не найдена секция 9"
    t = t[:m.start()] + S9[folder] + t[m.end():]

    # 2) блок таблиц протокола -> план верификации
    t = re.sub(r"### Ключевые таблицы протокола испытаний[^\n]*\n.*?(?=\n## 10\.)",
               "### План верификации\n\nМетодика испытаний (стендовый и модельный этапы) разработана и зафиксирована в рабочем журнале; выполнение проверок — по календарному плану (раздел 6). Натурные испытания на дату подачи не проводились.\n",
               t, flags=re.S)

    # 3) убрать «(источник: ...)»
    t = re.sub(r"\s*\(источник: `[^`]+`\)", "", t)

    # 4) приложения: описание протокола
    t = re.sub(r"(`docs/протокол_испытаний\.md` — )протокол[^\n]*",
               r"\1методика испытаний и план верификации", t)

    # 5) точечные правки
    misses = []
    for item in FIXES.get(folder, []):
        if len(item) == 3:
            _, pat, repl = item
            t2 = re.sub(pat, repl, t)
            if t2 == t:
                misses.append(pat[:70])
            t = t2
        else:
            old, new = item
            if old in t:
                t = t.replace(old, new)
            else:
                misses.append(old[:70])
    if misses:
        report.append((folder, misses))

    # 6) данные авторов
    author = folder.split("/")[0]
    if author in AUTHORS:
        a = AUTHORS[author]
        t = re.sub(r"- Ф\.И\.О\. автора: [^\n]*", f"- Ф.И.О. автора: {a['фио']}", t)
